    private String password;
    @Temporal(javax.persistence.TemporalType.DATE)
    @Column(name="CREATION_DATE")
    private Date creationDate;
    

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public SalonOwner() {
    }       

    @Override
    public int hashCode() {
        int hash = 0;
        hash += (id != null ? id.hashCode() : 0);
        return hash;
    }

